//! The plan document: what `.aicontext/plans/` holds after a plan-mode run.
//!
//! One markdown file per task, overwritten on a re-run: a plan is the current answer for a task,
//! not a log of the answers it used to give, and `.aicontext/` is local state rather than something
//! a commit reviews (`docs/CLI_SPEC.md` §4 — the command "writes to `.aicontext/plans/`" and
//! "modifies nothing" else). The file carries the model's plan, the context it was grounded in, and
//! the usage it cost, so a reviewer can judge the plan without re-running the call.

use std::fmt::Write as _;

use crate::agent::proposal::{Action, Proposal};

/// The directory a plan is written under, as a report spells it.
pub(crate) const PLANS_PATH: &str = ".aicontext/plans";

/// The file name a task's plan gets: the task id, with nothing outside `[A-Za-z0-9._-]` replaced.
///
/// The id normally arrives from the register, but it is typed by a human in `.ai/TASKS.md` and the
/// path is built from it here, so the one place a stray `../` could turn a plan into a write
/// elsewhere is this function. The run's own task lookup rejects ids the register does not declare,
/// and this closes the remaining gap for ids the register declares oddly.
#[must_use]
pub(crate) fn filename(task_id: &str) -> String {
    let safe: String = task_id
        .chars()
        .map(|character| {
            if character.is_ascii_alphanumeric() || matches!(character, '-' | '_' | '.') {
                character
            } else {
                '_'
            }
        })
        .collect();
    format!("{safe}.md")
}

/// Everything the renderer knows besides the plan itself.
pub(crate) struct Meta<'a> {
    /// The task id, which titles the document.
    pub(crate) task_id: &'a str,
    /// The task's title, when the register gave it one.
    pub(crate) task_title: Option<&'a str>,
    /// The task's status, as the register wrote it.
    pub(crate) task_status: Option<&'a str>,
    /// The provider line, for example `local (openai-compatible) test-model`.
    pub(crate) provider: &'a str,
    /// The context sources the packet actually held, as `id (tier n) path` lines.
    pub(crate) sources: &'a [String],
    /// The usage line, already spelled.
    pub(crate) usage: &'a str,
    /// Whether the model hit the output-token ceiling.
    pub(crate) truncated: bool,
}

/// The model's answer, after [`super::proposal::parse`] has decided which one it is.
pub(crate) enum Body {
    /// A validated proposal, whose sections are rendered from its actions.
    Structured(Proposal),
    /// A prose plan, rendered verbatim.
    Prose(String),
}

/// Renders the plan document.
#[must_use]
pub(crate) fn render(meta: &Meta<'_>, body: &Body) -> String {
    let mut out = String::new();
    let title = meta.task_title.unwrap_or("(untitled)");
    let _ = writeln!(out, "# Plan — {}: {}", meta.task_id, title);
    let _ = writeln!(out);
    let status = meta.task_status.unwrap_or("unrecorded");
    let _ = writeln!(
        out,
        "Status `{status}`. Generated by `aicontext agent run` in plan mode; nothing was executed."
    );
    let _ = writeln!(out);
    let _ = writeln!(out, "Provider: {}", meta.provider);
    let _ = writeln!(out);

    match body {
        Body::Structured(proposal) => render_proposal(&mut out, proposal),
        Body::Prose(text) => {
            let _ = writeln!(out, "## Plan");
            let _ = writeln!(out);
            let _ = writeln!(out, "{text}");
            let _ = writeln!(out);
        }
    }

    let _ = writeln!(out, "## Context sources");
    let _ = writeln!(out);
    if meta.sources.is_empty() {
        let _ = writeln!(out, "None: the packet held no documents.");
        let _ = writeln!(out);
    } else {
        for source in meta.sources {
            let _ = writeln!(out, "- {source}");
        }
        let _ = writeln!(out);
    }

    let _ = writeln!(out, "## Usage");
    let _ = writeln!(out);
    let _ = writeln!(out, "{}", meta.usage);
    if meta.truncated {
        let _ = writeln!(
            out,
            "The model hit the output-token ceiling, so the plan above may be incomplete."
        );
    }
    out
}

/// The proposal's sections: summary, files, risks, and the tool calls nothing executed.
fn render_proposal(out: &mut String, proposal: &Proposal) {
    let plans: Vec<_> = proposal
        .actions
        .iter()
        .filter(|action| matches!(action, Action::Plan { .. }))
        .collect();
    let tool_calls: Vec<_> = proposal
        .actions
        .iter()
        .filter(|action| matches!(action, Action::ToolCall { .. }))
        .collect();

    let _ = writeln!(out, "## Summary");
    let _ = writeln!(out);
    for action in &plans {
        if let Action::Plan { summary, .. } = action {
            let _ = writeln!(out, "{summary}");
            let _ = writeln!(out);
        }
    }

    for (heading, files) in [
        ("Files to modify", field(&plans, Which::Modify)),
        ("Files to create", field(&plans, Which::Create)),
        ("Files to delete", field(&plans, Which::Delete)),
    ] {
        let _ = writeln!(out, "## {heading}");
        let _ = writeln!(out);
        if files.is_empty() {
            let _ = writeln!(out, "None proposed.");
        } else {
            for file in files {
                let _ = writeln!(out, "- `{file}`");
            }
        }
        let _ = writeln!(out);
    }

    let mut risks: Vec<&String> = Vec::new();
    for action in &plans {
        if let Action::Plan { risks: more, .. } = action {
            risks.extend(more);
        }
    }
    if !risks.is_empty() {
        let _ = writeln!(out, "## Risks");
        let _ = writeln!(out);
        for risk in risks {
            let _ = writeln!(out, "- {risk}");
        }
        let _ = writeln!(out);
    }

    if !tool_calls.is_empty() {
        let _ = writeln!(out, "## Proposed tool calls (not executed)");
        let _ = writeln!(out);
        for action in &tool_calls {
            if let Action::ToolCall {
                tool, arguments, ..
            } = action
            {
                let _ = writeln!(out, "- `{tool}` — {arguments}");
            }
        }
        let _ = writeln!(out);
    }
}

/// Which file list of the plan actions is being rendered.
#[derive(Clone, Copy)]
enum Which {
    Modify,
    Create,
    Delete,
}

/// One file list, merged across every plan action, in the order written.
fn field<'a>(plans: &[&'a Action], which: Which) -> Vec<&'a str> {
    let mut files = Vec::new();
    for action in plans {
        if let Action::Plan {
            files_modify,
            files_create,
            files_delete,
            ..
        } = action
        {
            let chosen = match which {
                Which::Modify => files_modify,
                Which::Create => files_create,
                Which::Delete => files_delete,
            };
            files.extend(chosen.iter().map(String::as_str));
        }
    }
    files
}

#[cfg(test)]
mod tests {
    use super::{Body, Meta, filename, render};
    use crate::agent::proposal::{self, Parsed};

    fn meta<'a>(usage: &'a str, sources: &'a [String]) -> Meta<'a> {
        Meta {
            task_id: "TASK-055",
            task_title: Some("Implement agent run"),
            task_status: Some("TODO"),
            provider: "local (openai-compatible) test-model",
            sources,
            usage,
            truncated: false,
        }
    }

    #[test]
    fn a_task_id_becomes_a_file_name_that_cannot_walk_out_of_the_directory() {
        assert_eq!(filename("TASK-055"), "TASK-055.md");
        assert_eq!(filename("../../etc/passwd"), ".._.._etc_passwd.md");
        assert_eq!(filename("a/b\\c"), "a_b_c.md");
    }

    #[test]
    fn a_structured_plan_renders_every_section_a_reviewer_needs() {
        let sources = [".ai/RULES.md (tier 2) .ai/RULES.md".to_string()];
        let text = "Implement the run, then update the register.";
        let proposal = match proposal::parse(
            r#"{"kind":"action_proposal","version":1,"actions":[{"type":"plan","summary":"Implement the run, then update the register.","files_modify":["crates/aicontext-cli/src/agent/mod.rs",".ai/TASKS.md"],"files_create":["crates/aicontext-cli/src/agent/mod.rs"],"risks":["a plan file could escape the directory"]},{"type":"tool_call","tool":"aws.ec2.describe","arguments":{"id":"i-1"},"reason":"context"}]}"#,
        ) {
            Parsed::Structured(proposal) => proposal,
            other => panic!("expected a structured proposal, got {other:?}"),
        };
        let rendered = render(
            &meta("in 10, out 20 — provider-reported", &sources),
            &Body::Structured(proposal),
        );
        for expected in [
            "# Plan — TASK-055: Implement agent run",
            "Status `TODO`",
            "## Summary",
            text,
            "## Files to modify",
            "- `crates/aicontext-cli/src/agent/mod.rs`",
            "## Files to create",
            "## Files to delete",
            "None proposed.",
            "## Risks",
            "- a plan file could escape the directory",
            "## Proposed tool calls (not executed)",
            "- `aws.ec2.describe`",
            "## Context sources",
            "## Usage",
            "in 10, out 20 — provider-reported",
        ] {
            assert!(
                rendered.contains(expected),
                "missing `{expected}` in:\n{rendered}"
            );
        }
        assert!(
            !rendered.contains("modifies nothing"),
            "the header says what ran"
        );
    }

    #[test]
    fn a_prose_plan_is_kept_verbatim_under_one_heading() {
        let sources = [".ai/RULES.md (tier 2) .ai/RULES.md".to_string()];
        let rendered = render(
            &meta("in 1, out 2 — host estimate", &sources),
            &Body::Prose("Do the thing.\nThen stop.".to_string()),
        );
        assert!(rendered.contains("## Plan"));
        assert!(rendered.contains("Do the thing.\nThen stop."));
        assert!(
            !rendered.contains("## Files to modify"),
            "prose has no file lists"
        );
    }

    #[test]
    fn a_truncated_run_says_so_next_to_the_usage() {
        let sources = [".ai/RULES.md (tier 2) .ai/RULES.md".to_string()];
        let mut meta = meta("in 1, out 4000 — provider-reported", &sources);
        meta.truncated = true;
        let rendered = render(&meta, &Body::Prose("Start".to_string()));
        assert!(rendered.contains("may be incomplete"));
    }
}
